"""Turns the Fish Audio voice lines in AltarModManager/voice_in/ into game sounds.

    python import_voice.py

Expects line1.mp3 ... line24.mp3 (wav/ogg/m4a also fine). Each is loudness
levelled (see ANGELIC below for optional reverb), saved as
resources/sfx/altar/oblivion_lineN.wav, registered in content/sounds.xml, and its
length is written to scripts/altar_voice.lua so subtitles stay in sync.
Missing lines are skipped; the cutscene then shows subtitles only.
"""
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
MOD = os.path.join(os.path.dirname(ROOT), "mods", "altar_core")
VOICE_IN = os.path.join(ROOT, "voice_in")
sys.path.insert(0, os.path.join(ROOT, "src"))
from altar_sounds import write_sounds_xml  # noqa: E402
SFX_DIR = os.path.join(MOD, "resources", "sfx", "altar")
# Isaac has been seen failing to open mod sounds from resources/sfx alone, so a
# copy also goes to <mod>/sfx so the path resolves whichever way the game looks.
SFX_MIRROR = os.path.join(MOD, "sfx", "altar")

LINES = [
    'Your mother heard a voice from above. She thought it was God.',
    "It wasn't. It was me.",
    'I followed you down. Through the basement, the womb, the dark... all the way to the Void.',
    "Delirium was only your fear. I'm what's left when even that is gone.",
    'No one is coming for you, Isaac. Not her. Not him. Not God.',
    "You always get back up. That's what makes it hurt.",
    "Fine. Then I'll burn the whole sky down with you.",
    "No... you don't get an ending. Come with me.",
    "Go on, Isaac. Cry. It's all you've ever done.",
    'Look up, Isaac.',
    'Kneel. Like she wanted you to.',
    'Everything falls to me eventually.',
    'Find the light. If you can.',
    "Hide in the chest again. I'll wait.",
    "No... I won't be forgotten again!",
    "Shh. Back in the chest, Isaac. Back where it's quiet.",
    'This is where stories end. Out here, nobody can hear you cry.',
    'Every star up here is someone nobody remembers.',
    'Round and round. Like the mobile over your bed.',
    "Wait... I can hear it. Someone's reading your story.",
    'Then finish it. Let them remember you.',
    # her farewell (22-24), over the death_in/ panels
    "So this is what it's like. To be part of the story.",
    "Tell your mother it was never God. It was only ever me.",
    "Goodnight, Isaac. Someone is still reading.",
]

# The Fish Audio "Umbra" takes are already angelic, so only level the loudness
# (no extra reverb). Set ANGELIC = True to add the reverb + shimmer treatment back.
ANGELIC = False
LEVEL = "loudnorm=I=-12:TP=-1.0:LRA=9"  # loud enough to sit over the battle music
FILTER = ("highpass=f=90,chorus=0.55:0.85:45|65:0.30|0.25:0.25|0.35:1.8|2.4,"
          "aecho=0.85:0.75:70|140|260:0.40|0.28|0.18," + LEVEL) if ANGELIC else LEVEL
# trim dead air at both ends (keeping a breath), then a soft fade in/out and a short tail
# of silence, so no line starts late or ends on a hard cut
TRIM = ("silenceremove=start_periods=1:start_threshold=-50dB:start_silence=0.08,areverse,"
        "silenceremove=start_periods=1:start_threshold=-50dB:start_silence=0.25,areverse")
SHAPE = "afade=t=in:d=0.04,areverse,afade=t=in:d=0.2,areverse,apad=pad_dur=0.3"
FILTER = TRIM + "," + FILTER + "," + SHAPE


def ffmpeg_exe():
    try:
        import imageio_ffmpeg
        return imageio_ffmpeg.get_ffmpeg_exe()
    except ImportError:
        sys.exit("imageio-ffmpeg is missing. Run tools/build.py once (it installs it), "
                 "or: pip install imageio-ffmpeg")


def duration(ff, path):
    out = subprocess.run([ff, "-i", path], capture_output=True, text=True).stderr
    m = re.search(r"Duration: (\d+):(\d+):(\d+\.\d+)", out)
    if not m:
        return 4.0
    h, mi, s = m.groups()
    return int(h) * 3600 + int(mi) * 60 + float(s)


def find_input(n):
    for ext in ("mp3", "wav", "ogg", "m4a", "flac"):
        p = os.path.join(VOICE_IN, f"line{n}.{ext}")
        if os.path.isfile(p):
            return p
    return None


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ff = ffmpeg_exe()
    os.makedirs(SFX_DIR, exist_ok=True)
    found = []
    for n, text in enumerate(LINES, 1):
        src = find_input(n)
        if not src:
            print(f"line{n}: missing (subtitles only)")
            continue
        out = os.path.join(SFX_DIR, f"oblivion_line{n}.wav")
        subprocess.run([ff, "-y", "-loglevel", "error", "-i", src, "-af", FILTER, "-ac", "1", "-ar", "44100",
                        "-c:a", "pcm_s16le", out], check=True)
        os.makedirs(SFX_MIRROR, exist_ok=True)
        shutil.copy2(out, os.path.join(SFX_MIRROR, os.path.basename(out)))
        secs = duration(ff, out)
        found.append((n, text, secs))
        print(f"line{n}: {secs:.1f}s -> {out}")

    write_sounds_xml(MOD)  # voice lines + any boss SFX

    lua = ["-- Generated by AltarModManager/tools/import_voice.py. Subtitle text and line lengths (30fps frames).",
           "return {"]
    have = {n: secs for n, _, secs in found}
    for n, text in enumerate(LINES, 1):
        frames = int(have[n] * 30) if n in have else 0
        sound = lua_str(f"Altar Oblivion Line {n}") if n in have else "nil"
        lua.append(f"\t{{ text = {lua_str(text)}, sound = {sound}, frames = {frames} }},")
    lua.append("}")
    with open(os.path.join(MOD, "scripts", "altar_voice.lua"), "w", encoding="utf-8") as f:
        f.write("\n".join(lua) + "\n")
    print(f"{len(found)}/{len(LINES)} voice lines imported")


if __name__ == "__main__":
    main()
